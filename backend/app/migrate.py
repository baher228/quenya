def _vinted_privacy(connection) -> None:
    """Stop retaining Vinted raw marketplace payloads and allow NULL raw_json."""
    connection.execute(
        "ALTER TABLE items ALTER COLUMN raw_json DROP NOT NULL"
    )
    connection.execute(
        "UPDATE items SET raw_json=NULL WHERE source='vinted'"
    )
    connection.execute(
        """CREATE INDEX IF NOT EXISTS idx_items_source_fetched
           ON items(source, fetched_at)"""
    )


def _cost_indexes(connection) -> None:
    """Additive indexes for catalogue scans and retention/availability probes."""
    connection.execute(
        """CREATE INDEX IF NOT EXISTS idx_items_tagged_fetched
           ON items(fetched_at DESC)
           WHERE tags_json IS NOT NULL"""
    )
    connection.execute(
        """CREATE INDEX IF NOT EXISTS idx_items_source_availability
           ON items(source, availability)
           WHERE availability IS NOT NULL"""
    )


MIGRATIONS: list[tuple[str, Callable[[Any], None]]] = [
    ("0001_baseline", _baseline),
    ("0002_jobs", _jobs),
    ("0003_rate_limits", _rate_limits),
    ("0004_vinted_privacy", _vinted_privacy),
    ("0005_cost_indexes", _cost_indexes),
]
LATEST_VERSION = MIGRATIONS[-1][0]


class MigrationBlocked(RuntimeError):
    pass


_BLOCKER_QUERY = """
SELECT pid, usename, application_name, state,
       age(clock_timestamp(), xact_start) AS xact_age, left(query, 200) AS query
FROM pg_stat_activity
WHERE datname = current_database()
  AND state IN ('idle in transaction', 'idle in transaction (aborted)')
  AND xact_start < clock_timestamp() - make_interval(secs => ?)
  AND pid <> pg_backend_pid()
ORDER BY xact_start
"""


def _idle_transaction_rows(connection, minimum_age_seconds: int):
    return connection.execute(
        _BLOCKER_QUERY,
        (minimum_age_seconds,),
    ).fetchall()


def _describe_blocker(row) -> tuple[Any, ...]:
    return (
        _row_value(row, "pid", 0),
        _row_value(row, "usename", 1),
        _row_value(row, "application_name", 2),
        _row_value(row, "state", 3),
        _row_value(row, "xact_age", 4),
        _row_value(row, "query", 5),
    )


def _log_blockers() -> None:
    try:
        with db.db_connection() as connection:
            blockers = _idle_transaction_rows(connection, 60)
    except Exception:
        logger.exception("Could not query idle-in-transaction migration blockers")
        return

    if not blockers:
        logger.error("No idle-in-transaction sessions older than 60s were found")
        return
    for row in blockers:
        pid, usename, application_name, state, xact_age, query = _describe_blocker(row)
        logger.error(
            "Migration lock blocker: pid=%s usename=%s application_name=%s "
            "state=%s xact_age=%s query=%s",
            pid,
            usename,
            application_name,
            state,
            xact_age,
            query,
        )


def _prepare_migration_table(connection) -> None:
    connection.execute("CREATE SCHEMA IF NOT EXISTS quenya")
    connection.execute(
        """CREATE TABLE IF NOT EXISTS schema_migrations (
               version TEXT PRIMARY KEY,
               applied_at TIMESTAMPTZ NOT NULL DEFAULT now()
           )"""
    )


def run(*, report_blockers: bool = True) -> list[str]:
    with db.db_connection() as connection:
        versions = pending(connection)

    applied: list[str] = []
    migrations = dict(MIGRATIONS)
    for version in versions:
        try:
            with db.db_connection() as connection:
                connection.acquire_advisory_xact_lock(
                    db._POSTGRES_INIT_ADVISORY_LOCK_KEY
                )
                connection.execute("SET LOCAL lock_timeout = '5s'")
                connection.execute("SET LOCAL statement_timeout = '120s'")
                _prepare_migration_table(connection)
                recorded = connection.execute(
                    "SELECT 1 FROM schema_migrations WHERE version = ?",
                    (version,),
                ).fetchone()
                if recorded is not None:
                    continue
                migrations[version](connection)
                connection.execute(
                    "INSERT INTO schema_migrations (version) VALUES (?)",
                    (version,),
                )
            applied.append(version)
        except LockNotAvailable as exc:
            logger.error("Migration %s failed because a lock timed out", version)
            if report_blockers:
                _log_blockers()
            raise MigrationBlocked(f"migration {version} blocked by lock timeout") from exc
    return applied


def _terminate_idle_transactions() -> int:
    terminated = 0
    with db.db_connection() as connection:
        blockers = _idle_transaction_rows(connection, 300)
        for blocker in blockers:
            pid, usename, application_name, state, xact_age, query = _describe_blocker(
                blocker
            )
            result = connection.execute(
                """SELECT pg_terminate_backend(pid)
                   FROM pg_stat_activity
                   WHERE pid = ?
                     AND datname = current_database()
                     AND state IN (
                         'idle in transaction',
                         'idle in transaction (aborted)'
                     )
                     AND xact_start < clock_timestamp() - interval '5 minutes'
                     AND pid <> pg_backend_pid()""",
                (pid,),
            ).fetchone()
            did_terminate = bool(
                result and _row_value(result, "pg_terminate_backend", 0)
            )
            logger.warning(
                "Terminated stale transaction pid=%s usename=%s "
                "application_name=%s state=%s xact_age=%s query=%s result=%s",
                pid,
                usename,
                application_name,
                state,
                xact_age,
                query,
                did_terminate,
            )
            terminated += int(did_terminate)
    return terminated


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Apply Quenya database migrations")
    parser.add_argument(
        "--check",
        action="store_true",
        help="exit 1 and print pending migrations without applying them",
    )
    parser.add_argument(
        "--terminate-idle-in-transaction",
        action="store_true",
        help="terminate idle transactions older than 5 minutes after a lock timeout",
    )
    args = parser.parse_args(argv)

    if args.check:
        with db.db_connection() as connection:
            migrations = pending(connection)
        if migrations:
            print("Pending migrations: " + ", ".join(migrations))
            return 1
        print(f"Database is up to date at {LATEST_VERSION}")
        return 0

    try:
        applied = run()
    except MigrationBlocked as exc:
        if not args.terminate_idle_in_transaction:
            logger.error("%s", exc)
            return 1
        try:
            terminated = _terminate_idle_transactions()
            logger.warning(
                "Terminated %s idle-in-transaction session(s); retrying migrations once",
                terminated,
            )
            applied = run()
        except Exception as retry_exc:
            logger.error("Migration retry failed: %s", retry_exc)
            return 1

    if applied:
        print("Applied migrations: " + ", ".join(applied))
    else:
        print(f"Database is up to date at {LATEST_VERSION}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
